# ЧИСЛЕННАЯ ПРОВЕРКА РЕЗОНАНСА
# ═══════════════════════════════════════════════════════════════════

def check_resonance(X_max=100000):
    """Проверяем резонанс при α = 1/4"""
    
    # Простое решето
    sieve = np.ones(X_max + 1, dtype=bool)
    sieve[0] = sieve[1] = False
    for i in range(2, int(X_max**0.5) + 1):
        if sieve[i]:
            sieve[i*i::i] = False
    primes = np.where(sieve)[0]
    
    def chi4(n):
        if n % 2 == 0:
            return 0
        return 1 if n % 4 == 1 else -1
    
    # F(α) = Σ Λ(p)·χ₄(p)·e(pα)
    alpha_values = [0, 0.25, 0.5, 0.125, 0.375]
    
    print("="*60)
    print(f"ПРОВЕРКА РЕЗОНАНСА (X = {X_max:,})")
    print("="*60)
    print(f"{'α':>10} | {'|F(α)|':>15} | {'|F(α)|/X':>12} | {'Комментарий':>15}")
    print("-"*60)
    
    for alpha in alpha_values:
        # F(α) = Σ log(p) · χ₄(p) · e(p·α)
        F = sum(np.log(p) * chi4(p) * np.exp(2j * np.pi * p * alpha) 
                for p in primes if p > 2)
        
        magnitude = abs(F)
        ratio = magnitude / X_max
        
        comment = ""
        if alpha == 0.25:
            comment = "← РЕЗОНАНС!"
        elif ratio < 0.01:
            comment = "(малое)"
        
        print(f"{alpha:>10.4f} | {magnitude:>15.2f} | {ratio:>12.6f} | {comment:>15}")
    
    print()
    print("Видим: |F(1/4)| ~ X, остальные ~ √X или меньше!")
    
    return

