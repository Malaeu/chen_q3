#!/usr/bin/env python3
"""Render the canonical registry as deterministic semantic Markdown."""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from orchestrator import session_briefing

REGISTRY = Path("docs/routeB_bus/RECHECKABLE_RESEARCH_DEBTS.json")
OUTPUT = Path("docs/routeB_bus/RESEARCH_DEPENDENCY_CLASSIFICATION.md")


def _cell(value: object) -> str:
    return " ".join(str(value).split()).replace("|", "\\|")


def render(repo: Path = REPO) -> bytes:
    registry_path = repo / REGISTRY
    registry = session_briefing.validate_registry(repo, registry_path)
    source_hash = hashlib.sha256(registry_path.read_bytes()).hexdigest()
    lines = [
        "# Route B research dependency classification",
        "",
        "<!-- GENERATED by orchestrator/research_dependency_projection.py; do not edit. -->",
        "",
        f"- Source: `{REGISTRY.as_posix()}`",
        f"- Source SHA-256: `{source_hash}`",
        "- Authority: semantic projection only; it does not select or reopen execution.",
        "",
        "## Recheckable research debts",
        "",
        "| ID | Goal | Original object | Consumer | Minimal sufficient direction | Status |",
        "|---|---:|---|---|---|---|",
    ]
    for row in registry["debts"]:
        sufficient = [
            audit["class"]
            for audit in row["alternative_interface_audit"]
            if audit["status"] == "SUFFICIENT_CANDIDATE"
        ]
        lines.append(
            "| "
            + " | ".join(
                _cell(value)
                for value in (
                    row["id"],
                    row["related_goal"],
                    row["original_object_is"],
                    row["actual_consumer_requirement"],
                    ", ".join(sufficient) or "No sufficient candidate classified",
                    row["status"],
                )
            )
            + " |"
        )
    lines.extend(
        [
            "",
            "## Mathematically dead — non-actionable",
            "",
            "These atomically scoped theorem shapes are excluded from search, ranking,",
            "dispatch, reopening and route selection. Their surviving interfaces are not",
            "the dead theorem shapes and require an independent consumer-first contract.",
            "",
        ]
    )
    for item in registry["adjudications"]:
        lines.extend(
            [
                f"### `{item['id']}`",
                "",
                f"- Scope: {_cell(item['scope'])}",
                f"- Obstruction: {_cell(item['dead_reason'])}",
                f"- Surviving interface: {_cell(item['surviving_interface'])}",
                "- Evidence:",
            ]
        )
        for ref in item["evidence_refs"]:
            lines.append(
                f"  - `{ref['path']}` at `{ref['commit']}` / blob `{ref['git_blob']}`: "
                f"{_cell(ref['claim'])}"
            )
        lines.append("")
    return ("\n".join(lines).rstrip() + "\n").encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("check", "stdout"))
    parser.add_argument("--root", type=Path, default=REPO)
    args = parser.parse_args()
    repo = args.root.resolve()
    expected = render(repo)
    if args.command == "stdout":
        sys.stdout.buffer.write(expected)
        return 0
    output = repo / OUTPUT
    if not output.is_file() or output.read_bytes() != expected:
        print("RESEARCH_DEPENDENCY_PROJECTION_STALE", file=sys.stderr)
        return 2
    print("RESEARCH_DEPENDENCY_PROJECTION_PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
