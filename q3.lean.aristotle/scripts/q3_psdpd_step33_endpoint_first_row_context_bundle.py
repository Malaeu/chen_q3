#!/usr/bin/env python3
"""Build a minimal Aristotle context bundle for the Step33 endpoint pilot.

The full Q3 project directory is too large to submit directly because `.lake`
dominates the checkout.  This script copies only the Lean source files reachable
from the first-row endpoint pilot plus a minimal Lake project skeleton into a
temporary directory.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_START = ROOT / "aristotle_input/step33_endpoint_v18_first_row_pilot.lean"
DEFAULT_PROOF_PACK = (
    ROOT / "aristotle_input/step33_endpoint_v18_first_row_proof_pack.md"
)
DEFAULT_OUT = Path("/tmp/q3_step33_endpoint_v18_first_row_context")


MINIMAL_LAKEFILE = """name = "q3_step33_endpoint_context"
version = "0.1.0"
defaultTargets = ["Q3"]

[[require]]
name = "mathlib"
scope = "leanprover-community"
rev = "v4.26.0"

[[lean_lib]]
name = "Q3"
moreLeanArgs = ["-j", "1", "-s", "65536"]
globs = ["Q3"]

[[lean_lib]]
name = "aristotle_output"
roots = ["aristotle_output"]
"""


README_TEMPLATE = """# Step33 Endpoint v18 First-Row Aristotle Context

Generated by:

```bash
python3 scripts/q3_psdpd_step33_endpoint_first_row_context_bundle.py
```

Validate inside this bundle with:

```bash
lake env lean aristotle_input/step33_endpoint_v18_first_row_pilot.lean
```

Submit after explicit user OK with:

```bash
source .venv/bin/activate
aristotle submit "Fill the two intentional endpoint proof holes in aristotle_input/step33_endpoint_v18_first_row_pilot.lean. Use the checked Q3 receivers named in aristotle_input/step33_endpoint_v18_first_row_proof_pack.md; do not add axioms, unsafe code, trusted numerical black boxes, admit, exact?, or theorem weakening. Return hole-free Lean proof replacements or the exact missing analytic lemma." --project-dir {out}
```
"""


def module_to_source(module: str) -> Path | None:
    if module.startswith("Mathlib") or module == "Qq":
        return None
    candidate = ROOT / f"{module.replace('.', '/')}.lean"
    if candidate.exists():
        return candidate
    return None


def imported_modules(path: Path) -> list[str]:
    modules: list[str] = []
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = raw.strip()
        if not line.startswith("import "):
            continue
        line = line.split("--", 1)[0].strip()
        modules.extend(line.split()[1:])
    return modules


def collect_sources(start: Path) -> list[Path]:
    seen: set[Path] = set()
    ordered: list[Path] = []

    def visit(path: Path) -> None:
        resolved = path.resolve()
        if resolved in seen:
            return
        seen.add(resolved)
        ordered.append(resolved)
        for module in imported_modules(resolved):
            source = module_to_source(module)
            if source is not None:
                visit(source)

    visit(start)
    return ordered


def copy_into_bundle(files: list[Path], proof_pack: Path, out: Path) -> None:
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for path in files + [proof_pack.resolve()]:
        rel = path.relative_to(ROOT)
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)

    (out / "lakefile.toml").write_text(MINIMAL_LAKEFILE, encoding="utf-8")
    shutil.copy2(ROOT / "lean-toolchain", out / "lean-toolchain")
    (out / "README.md").write_text(
        README_TEMPLATE.format(out=out),
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--start", type=Path, default=DEFAULT_START)
    parser.add_argument("--proof-pack", type=Path, default=DEFAULT_PROOF_PACK)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    files = collect_sources(args.start)
    copy_into_bundle(files, args.proof_pack, args.out)
    total_bytes = sum(path.stat().st_size for path in files)
    print(f"bundle: {args.out}")
    print(f"source_files: {len(files)}")
    print(f"source_bytes: {total_bytes}")
    print("submit_project_dir:", args.out)


if __name__ == "__main__":
    main()
